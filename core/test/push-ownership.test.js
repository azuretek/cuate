import { test } from 'node:test';
import assert from 'node:assert/strict';
const defined = {};
globalThis.HTMLElement = class { addEventListener() {} removeAttribute() {} setAttribute() {} hasAttribute() { return false; } getAttribute() { return null; } dispatchEvent() {} };
globalThis.customElements = { define(name, cls) { defined[name] = cls; }, get() { return undefined; } };
globalThis.document = { hidden: true, visibilityState: 'hidden', createTreeWalker() { return {}; }, createComment() { return {}; }, importNode() { return {}; }, createElement() { return { content: {} }; } };
await import('../app/components/app-root.js');
const AppRoot = defined['app-root'];

test('the actual page selects remote delivery before registration settles, falls back on refusal and ignores stale clients', async () => {
  const page = new AppRoot();
  page.notifyPermission = 'granted';
  page.bridge = async () => ({ token: 'synthetic', platform: 'ios', key: 'synthetic' });
  let release;
  page.client = { pushRegister: () => new Promise((resolve) => { release = resolve; }) };
  const registering = page.registerPush();
  await Promise.resolve();
  assert.equal(page.pushRegistered, true, 'no local twin during registration response race');
  release();
  assert.equal(await registering, true);
  page.client = { pushRegister: async () => { throw new Error('synthetic refusal'); } };
  assert.equal(await page.registerPush(), false);
  assert.equal(page.pushRegistered, false);
  let rejectOld;
  page.client = { pushRegister: () => new Promise((_, reject) => { rejectOld = reject; }) };
  const stale = page.registerPush();
  await Promise.resolve();
  page.client = { pushRegister: async () => {} };
  assert.equal(await page.registerPush(), true);
  rejectOld(new Error('stale refusal'));
  assert.equal(await stale, false);
  assert.equal(page.pushRegistered, true, 'stale refusal cannot clear the new owner');
  page.notifyPermission = 'denied';
  assert.equal(await page.registerPush(), false);
});

test('the actual message event raises local notices only without a remote owner and respects preferences and event rows', () => {
  const page = new AppRoot();
  const notices = [];
  page.bridge = async (name, value) => { if (name === 'notify') notices.push(value); };
  page.reconcile = () => {};
  page.reload = () => {};
  page.chats = [{ id: '1', name: 'Synthetic', unread: 0, participants: [], lastMessageAt: null, lastMessage: null }];
  const message = { id: 'synthetic-1', chatId: '1', text: 'Synthetic notice', fromMe: false, sentAt: '2026-01-01T00:00:00Z', attachments: [] };
  const event = (extra = {}) => page.onEvent({ name: 'message.new', data: { message: { ...message, ...extra } } });
  page.pushRegistered = true;
  event();
  assert.equal(notices.length, 0);
  page.pushRegistered = false;
  event();
  assert.equal(notices.length, 1);
  assert.equal(notices[0].messageId, message.id);
  page.settings = { 'notifications.newMessage': false };
  event();
  assert.equal(notices.length, 1);
  page.settings = {};
  event({ fromMe: true });
  event({ event: { kind: 'rename' } });
  assert.equal(notices.length, 1);
});
