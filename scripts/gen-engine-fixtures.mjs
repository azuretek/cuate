export function fixtures() {
  return {
    description: 'The answer sheet every engine is held to: Node through the source modules, JavaScriptCore and the Android embedded engine through the committed bundle. Generated by scripts/gen-engine-fixtures.mjs from the rules; do not edit.',
    cases: CASES.map((c) => ({ ...c, expect: JSON.stringify(engine[c.call](...c.args)) })),
  };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const file = JSON.stringify(fixtures(), null, 2) + '\n';
  if (process.argv.includes('--check')) {
    let current = null;
    try {
      current = readFileSync(OUT, 'utf8');
    } catch {
      console.error('core/fixtures/engine-cases.json is missing: run pnpm run fixtures');
      process.exit(1);
    }
    if (current !== file) {
      console.error('core/fixtures/engine-cases.json is stale: run pnpm run fixtures');
      process.exit(1);
    }
    console.log('core/fixtures/engine-cases.json is fresh');
  } else {
    writeFileSync(OUT, file);
    console.log('wrote core/fixtures/engine-cases.json');
  }
}
