// Writes core/fixtures/engine-cases.json from the cases declared here; --check
// fails when the committed file is stale, the way gen-tokens.mjs and
// gen-engine-bundle.mjs do.
//
// The cases are the shared answer sheet every engine is held to. Node runs them
// against the source modules (core/test/fixtures.test.js), and each shell runs
// the same cases through its native engine: JavaScriptCore on iOS, the embedded
// engine on Android. A case is JSON in and a JSON string out, so it travels to a
// shell as data rather than as code.
//
// Inputs are synthetic: handled at example.com, numbers in the fictional
// 555-555-01xx range, and text written here. A home path is built from parts so
// the publish scan, which looks for real ones, finds no literal path in this
// file.
